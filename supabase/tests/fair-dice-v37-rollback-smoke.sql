  perform set_config('request.headers', jsonb_build_object('x-guest-id', guest_id, 'x-guest-proof', guest_proof,
    'x-client-info', 'supabase-js-web/smoke nardu-fair-dice-v36 nardu-fair-dice-v37')::text, true);
  insert into public.rooms(code,variant,status,host_name,host_guest_id,host_registered,game_state,fair_dice_required,fair_dice_protocol)
