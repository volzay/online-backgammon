  if ledger.round is not null or ledger.private_seed !~ '^[0-9a-f]{64}$'
     or ledger.commitment <> private.system_fair_dice_commitment(ledger)
     or ledger.client_seed is not null or ledger.client_seed_at is not null then
    raise exception 'System entropy was not created exactly once before the client challenge.';
  end if;
  result := public.get_fair_dice_request(request_id);
  room_result := public.get_fair_dice_room(fixture_code);
  if result ? 'privateSeed' or result#>'{request,privateSeed}' is not null
     or room_result#>'{pending,privateSeed}' is not null
     or room_result#>'{pending,request,privateSeed}' is not null then
    raise exception 'Unrevealed server entropy escaped into public receipts.';
  end if;
  begin
    perform public.accept_system_fair_dice_client_seed(request_id,repeat('2',64),fixture_code,first_epoch,receipt->>'positionHash');
    raise exception 'An anonymous player called the privileged acceptance RPC.';
  exception when insufficient_privilege then null; end;
  perform set_config('request.jwt.claims', '{"role":"service_role"}', true);
  perform set_config('request.jwt.claim.role', 'service_role', true);
  begin
    perform public.commit_fair_dice_proof(request_id,'{}'::jsonb);
    raise exception 'A seed was revealed before accepting a client challenge.';
  exception when check_violation then null; end;
  begin
    perform public.accept_system_fair_dice_client_seed(request_id,repeat('2',64),fixture_code,gen_random_uuid(),receipt->>'positionHash');
    raise exception 'A wrong game epoch accepted the client challenge.';
  exception when check_violation then null; end;
  begin
    perform public.accept_system_fair_dice_client_seed(request_id,repeat('2',64),fixture_code,first_epoch,repeat('f',64));
