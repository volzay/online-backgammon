    raise exception 'v37 private entropy or service capability ACL is invalid.';
  end if;
  -- Golden vectors are independently generated by the Node prototype and shared
  -- browser protocol. They catch PostgreSQL JSON whitespace/nested escaping drift.
  vector.id := '22222222-2222-4222-8222-222222222222';
  vector.game_id := '11111111-1111-4111-8111-111111111111';
  vector.room_code := 'V37A-ABCD'; vector.nonce := 1; vector.variant := 'long';
