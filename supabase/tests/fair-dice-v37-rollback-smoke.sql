-- Installers have BEGIN/COMMIT wrappers: strip them in the harness, never commit
-- this synthetic fixture. HMAC/context are real; Ed25519 bytes are synthetic
-- because the privileged service verifies the coordinator signature separately.
do $fair_dice_v37_smoke$
declare
